-- reconciliation-service. Spring Batch 6 metadata tables (copied from spring-batch-core schema-postgresql.sql), then recon tables.


CREATE TABLE BATCH_JOB_INSTANCE (
	JOB_INSTANCE_ID BIGINT  NOT NULL PRIMARY KEY,
	VERSION BIGINT,
	JOB_NAME VARCHAR(100) NOT NULL,
	JOB_KEY VARCHAR(32) NOT NULL,
	constraint JOB_INST_UN unique (JOB_NAME, JOB_KEY)
) ;

CREATE TABLE BATCH_JOB_EXECUTION (
	JOB_EXECUTION_ID BIGINT  NOT NULL PRIMARY KEY,
	VERSION BIGINT,
	JOB_INSTANCE_ID BIGINT NOT NULL,
	CREATE_TIME TIMESTAMP NOT NULL,
	START_TIME TIMESTAMP DEFAULT NULL,
	END_TIME TIMESTAMP DEFAULT NULL,
	STATUS VARCHAR(10),
	EXIT_CODE VARCHAR(2500),
	EXIT_MESSAGE VARCHAR(2500),
	LAST_UPDATED TIMESTAMP,
	constraint JOB_INST_EXEC_FK foreign key (JOB_INSTANCE_ID)
	references BATCH_JOB_INSTANCE(JOB_INSTANCE_ID)
) ;

CREATE TABLE BATCH_JOB_EXECUTION_PARAMS (
	JOB_EXECUTION_ID BIGINT NOT NULL,
	PARAMETER_NAME VARCHAR(100) NOT NULL,
	PARAMETER_TYPE VARCHAR(100) NOT NULL,
	PARAMETER_VALUE VARCHAR(2500),
	IDENTIFYING CHAR(1) NOT NULL,
	constraint JOB_EXEC_PARAMS_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE TABLE BATCH_STEP_EXECUTION (
	STEP_EXECUTION_ID BIGINT  NOT NULL PRIMARY KEY,
	VERSION BIGINT NOT NULL,
	STEP_NAME VARCHAR(100) NOT NULL,
	JOB_EXECUTION_ID BIGINT NOT NULL,
	CREATE_TIME TIMESTAMP NOT NULL,
	START_TIME TIMESTAMP DEFAULT NULL,
	END_TIME TIMESTAMP DEFAULT NULL,
	STATUS VARCHAR(10),
	COMMIT_COUNT BIGINT,
	READ_COUNT BIGINT,
	FILTER_COUNT BIGINT,
	WRITE_COUNT BIGINT,
	READ_SKIP_COUNT BIGINT,
	WRITE_SKIP_COUNT BIGINT,
	PROCESS_SKIP_COUNT BIGINT,
	ROLLBACK_COUNT BIGINT,
	EXIT_CODE VARCHAR(2500),
	EXIT_MESSAGE VARCHAR(2500),
	LAST_UPDATED TIMESTAMP,
	constraint JOB_EXEC_STEP_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE TABLE BATCH_STEP_EXECUTION_CONTEXT (
	STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
	SHORT_CONTEXT VARCHAR(2500) NOT NULL,
	SERIALIZED_CONTEXT TEXT,
	constraint STEP_EXEC_CTX_FK foreign key (STEP_EXECUTION_ID)
	references BATCH_STEP_EXECUTION(STEP_EXECUTION_ID)
) ;

CREATE TABLE BATCH_JOB_EXECUTION_CONTEXT (
	JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
	SHORT_CONTEXT VARCHAR(2500) NOT NULL,
	SERIALIZED_CONTEXT TEXT,
	constraint JOB_EXEC_CTX_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE SEQUENCE BATCH_STEP_EXECUTION_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
CREATE SEQUENCE BATCH_JOB_EXECUTION_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
CREATE SEQUENCE BATCH_JOB_INSTANCE_SEQ MAXVALUE 9223372036854775807 NO CYCLE;

CREATE TABLE recon_runs (
    id               UUID PRIMARY KEY,
    job_name         VARCHAR(40)  NOT NULL CHECK (job_name IN ('PG_VS_LEDGER', 'TRANSFERS_VS_UPI', 'WALLET_INTEGRITY')),
    business_date    DATE         NOT NULL,
    window_from      TIMESTAMPTZ  NOT NULL,
    window_to        TIMESTAMPTZ  NOT NULL,
    status           VARCHAR(10)  NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    triggered_by     VARCHAR(100) NOT NULL,
    left_count       INT          NOT NULL DEFAULT 0,
    right_count      INT          NOT NULL DEFAULT 0,
    matched_count    INT          NOT NULL DEFAULT 0,
    mismatch_count   INT          NOT NULL DEFAULT 0,
    error            VARCHAR(500),
    job_execution_id BIGINT,
    started_at       TIMESTAMPTZ  NOT NULL,
    finished_at      TIMESTAMPTZ,
    version          BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX idx_recon_runs_job ON recon_runs (job_name, started_at DESC);

-- staging: both sides of a comparison, keyed by the shared reference
CREATE TABLE recon_records (
    run_id      UUID          NOT NULL REFERENCES recon_runs (id),
    side        VARCHAR(5)    NOT NULL CHECK (side IN ('LEFT', 'RIGHT')),
    reference   VARCHAR(120)  NOT NULL,
    amount      NUMERIC(19,2) NOT NULL,
    occurred_at TIMESTAMPTZ   NOT NULL,
    in_window   BOOLEAN       NOT NULL,
    PRIMARY KEY (run_id, side, reference)
);

CREATE TABLE recon_mismatches (
    id              UUID PRIMARY KEY,
    run_id          UUID          NOT NULL REFERENCES recon_runs (id),
    job_name        VARCHAR(40)   NOT NULL,
    type            VARCHAR(40)   NOT NULL,
    reference       VARCHAR(120)  NOT NULL,
    expected_amount NUMERIC(19,2),
    actual_amount   NUMERIC(19,2),
    status          VARCHAR(10)   NOT NULL CHECK (status IN ('OPEN', 'RESOLVED')),
    note            VARCHAR(500),
    resolved_by     VARCHAR(100),
    resolved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0,
    UNIQUE (run_id, type, reference)
);
CREATE INDEX idx_recon_mismatches_status ON recon_mismatches (status, created_at DESC);
